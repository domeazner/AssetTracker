using AssetTracker.Data;
using AssetTracker.Services;
using AssetTracker.UI;
using Microsoft.Extensions.Configuration;

namespace AssetTracker;


/// <summary>
/// Application entry point and unique location in the application where modules are composed together. This is the only place where the concrete classes are created and wired together (constructor dependency injection), so every other class depends on abstractions and stays easy to test and replace.
///
/// Stages:
/// 
/// 1) Initialise Windows Forms
/// 2) Load the connection string from appsettings.json 
/// 3) Build the layers from the bottom up through the process of Data > Service > UI
/// 4) Add Asset form opening 
/// 
/// </summary>

static class Program
{

    /// Windows Forms requires the UI thread to run in single threaded apartment mode.

    [STAThread]
    static void Main()
    {

        /// Action 1: Standard WinForms setup (high-DPI settings, default font, visual styles). Generated by .NET 8 and must run before any form is created.

        ApplicationConfiguration.Initialize();


        /// Action 2: Read configuration from appsettings.json, located next to the .exe. Optional action: false means the app fails immediately with a clear error if the file is missing, rather than failing later with a misleading database error. The real file is untracked in Git because it holds credentials; only appsettings.example.json is committed.

        var config = new ConfigurationBuilder()
            .SetBasePath(AppContext.BaseDirectory)
            .AddJsonFile("appsettings.json", optional: false)
            .Build();

        /// Get the Azure SQL connection string named "AssetDb". The ! tells the compiler we expect it to exist.

        string connectionString = config.GetConnectionString("AssetDb")!;


        /// Action 3: Layer Construction, Data layer: the repositories that run parameterised SQL against Azure SQL. Each one receives the connection string through its constructor.

        var employeeRepository = new SqlEmployeeRepository(connectionString);

        /// Service layer: AssetService holds the validation rules and talks to the database only through the IAssetRepository interface. Here we give it the SQL implementation but a test can pass in a fake one instead.

        var assetService = new AssetService(new SqlAssetRepository(connectionString));


        /// Action 4: Start the UI and keep the app running until the form is closed. The form receives everything it needs rather than creating it itself:
        ///   assetService          > validates and saves the new asset
        ///   HardwareInfoCollector > reads this machine's details (via WMI) to auto-fill the form
        ///   employeeRepository    > loads employees to fill the owner dropdown

        Application.Run(new AddAssetForm(assetService, new HardwareInfoCollector(), employeeRepository));
    }
}